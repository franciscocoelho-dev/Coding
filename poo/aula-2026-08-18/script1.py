# Definimos uma classe chamada "Produto".
# A palavra "class" indica que estamos criando um novo tipo de dado.
# "pass" significa que a classe está vazia por enquanto (não tem atributos nem métodos).
class Produto:
    pass

# Aqui criamos um OBJETO a partir da classe Produto.
# Isso é chamado de "instanciar a classe".
# p1 é uma instância (um exemplar) da classe Produto.
p1 = Produto()


# type() mostra o tipo do objeto que estamos usando.
# Como p1 foi criado a partir da classe Produto,
# o resultado será algo como: <class '__main__.Produto'>
print(type(p1))



